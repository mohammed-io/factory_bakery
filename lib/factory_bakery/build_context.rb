# frozen_string_literal: true

module FactoryBakery
  # Records the bake calls currently in flight. Every public `bake` pushes the
  # resolved class and pops it in an `ensure`, so a declaration block that bakes
  # again sees the classes above it and runaway recursion becomes a clear error
  # instead of a SystemStackError.
  #
  # The stack is stored fiber-locally (Fiber[] storage is inherited by child
  # fibers but never shared between threads). The value is replaced rather than
  # mutated, so a child fiber that inherited a parent's context can never mutate
  # the parent's stack.
  #
  # A separate fiber-local registry records every object generated by a
  # top-level bake, tagged with the path it was generated at. `bake!` uses it to
  # verify that the whole graph was persisted after the root `save!`. The
  # registry is created and cleared at the top-level boundary, so each bake is
  # isolated even when declarations nest arbitrarily.
  #
  # A third fiber-local map is the associations plugin's in-graph sharing
  # cache. It maps a strict match key (exact class + association scope +
  # scalar overrides) to the object built for it. Like the generated records it
  # is created and cleared at the top-level boundary, so a nested bake can read
  # its parent's completed objects but no state leaks across bakes, threads or
  # fibers.
  #
  # A fourth fiber-local slot holds the object whose rules are being resolved
  # right now. The core binds it around heuristic generation as an opaque
  # value; a mapper may read it to resolve rules that depend on the live
  # record. It is saved and restored so nested bakes cannot leak their object
  # outward.
  #
  # A fifth fiber-local map caches validator-condition outcomes per
  # record/validator/attribute for one bake. The same rule is read several
  # times while a bake partitions, routes and verifies attributes; evaluating
  # a user-supplied condition that often was observable. It is cleared at the
  # top-level boundary and never mutated in place.
  #
  # A sixth fiber-local map is the uniqueness enforcer's per-top-level-bake
  # registry: every value it accepted, keyed by table identity, attribute and
  # normalized value. Two unsaved records built in the same graph (two parents
  # of different edges, say) are invisible to the database's own uniqueness
  # check, so the enforcer treats a value already in this map as a collision.
  # It is created and cleared at the top-level boundary and replaced rather
  # than mutated, like the maps above.
  class BuildContext # rubocop:disable Metrics/ClassLength
    STORAGE_KEY = :factory_bakery_build_context
    RECORDS_KEY = :factory_bakery_generated_records
    GRAPH_CACHE_KEY = :factory_bakery_graph_cache
    RECORD_KEY = :factory_bakery_current_record
    CONDITIONS_KEY = :factory_bakery_condition_results
    UNIQUE_VALUES_KEY = :factory_bakery_unique_values
    # FK-column-validated edges need a persisted parent. Under `bake!` that
    # parent is inserted inside the root savepoint; under plain `bake` it is an
    # explicit, documented exception to the unsaved graph. This fiber-local
    # flag tells the associations plugin which contract is active without
    # coupling it to factory_bakery's public methods.
    PERSIST_PARENTS_KEY = :factory_bakery_persist_fk_parents

    class << self
      def current
        Fiber[STORAGE_KEY] ||= new([].freeze)
      end

      # Every generated object, paired with the build path it was generated at.
      def generated_records
        Fiber[RECORDS_KEY] ||= []
      end

      def record_generated(object)
        generated_records << [current.path, object]
      end

      # Swaps an object the bake built for the object that ends up in the
      # graph. An FK-presence parent that cannot be written (a read-only
      # model) is replaced by the existing row it adopted, so `bake!`
      # verifies and guards the assigned record rather than the unsaved one
      # it was built from. Replaced, not mutated, like the trim below.
      def replace_generated!(from, to)
        return if from.equal?(to)

        Fiber[RECORDS_KEY] = generated_records.map do |path, object|
          object.equal?(from) ? [path, to] : [path, object]
        end
      end

      # Discards records from a build whose result is thrown away (a failed
      # first attempt before the verified fallback rebuild), along with the
      # strategy :reuse cache entries pointing at them: the rebuild must not
      # hand out an object from an attempt whose writes were rolled back.
      # Replace rather than mutate so a child fiber that inherited the
      # array/map is unaffected.
      def trim_generated_records!(mark)
        records = generated_records
        return if records.length <= mark

        discarded = records.drop(mark).map { |_path, object| object.object_id }
        Fiber[RECORDS_KEY] = records.first(mark)
        stale = graph_cache.reject { |_key, (_path, object)| discarded.include?(object.object_id) }
        Fiber[GRAPH_CACHE_KEY] = stale
      end

      # Per-top-level-bake cache used by :reuse edges. The value is a pair of
      # the build path (nil for an object adopted from the database) and the
      # object itself, so a lookup can refuse an ancestor still being built.
      def graph_cache
        Fiber[GRAPH_CACHE_KEY] ||= {}
      end

      def graph_object(key)
        graph_cache[key]
      end

      def record_graph_object(key, path, object)
        # Replace rather than mutate: a child fiber inherits the parent's map
        # and must never write back into it.
        Fiber[GRAPH_CACHE_KEY] = graph_cache.merge(key => [path, object])
      end

      # True while a `bake!` is building its graph (including nested bakes made
      # from declaration blocks). FK-presence parents created here are inserted
      # inside that bake's savepoint and roll back with it.
      def persisting?
        Fiber[PERSIST_PARENTS_KEY] || false
      end

      def with_persistence
        previous = Fiber[PERSIST_PARENTS_KEY]
        Fiber[PERSIST_PARENTS_KEY] = true
        yield
      ensure
        Fiber[PERSIST_PARENTS_KEY] = previous
      end

      # The object currently being filled, or nil outside value generation.
      # It is deliberately opaque to the core: only a mapper interprets it.
      def current_record
        Fiber[RECORD_KEY]
      end

      def with_record(object)
        previous = Fiber[RECORD_KEY]
        Fiber[RECORD_KEY] = object
        yield
      ensure
        Fiber[RECORD_KEY] = previous
      end

      # Cached condition outcome for one (record, validator, attribute) in the
      # current bake. nil means "not evaluated yet"; results are booleans. The
      # map is read-only here and replaced on write, so an inherited child
      # fiber can never change its parent's results.
      def condition_result(key)
        Fiber[CONDITIONS_KEY]&.[](key)
      end

      def record_condition_result(key, result)
        Fiber[CONDITIONS_KEY] = (Fiber[CONDITIONS_KEY] || {}).merge(key => result)
      end

      # Assignments can change the value a condition reads (an if:/unless:
      # guard on an override is the common case), so results cached before a
      # batch of setters run are stale. The builder drops them at each
      # assignment phase; the map itself stays scoped to this bake and fiber.
      def invalidate_condition_results!
        Fiber[CONDITIONS_KEY] = {}
      end

      # True when a uniqueness value generated earlier in this same bake
      # already took the key. The key is [table identity, attribute, normalized
      # value]; the enforcer owns its shape. The map is read-only here and
      # replaced on write, so an inherited child fiber can never change its
      # parent's registry.
      def unique_value_taken?(key)
        unique_values.key?(key)
      end

      def record_unique_value(key)
        # Replace rather than mutate, for the same reason as the graph cache.
        Fiber[UNIQUE_VALUES_KEY] = unique_values.merge(key => true)
      end

      def unique_values
        Fiber[UNIQUE_VALUES_KEY] ||= {}
      end

      # Records generated at or below `path_prefix`. This scopes a nested
      # `bake!` to its own subtree instead of failing on a sibling's unsaved
      # object that the root `bake!` will verify later.
      def records_under(path_prefix)
        length = path_prefix.length
        generated_records.select { |path, _object| path[0, length] == path_prefix }
      end

      # The most recently completed object of exactly `klass` that is not an
      # ancestor still being built. Within one top-level bake the graph is
      # shared: a parent class built once (for example the user behind two
      # different belongs_to edges) is handed to every later edge instead of
      # being built again. An ancestor's recorded path is a prefix of the
      # current path, so reusing one would close a cycle; those are skipped.
      def completed_object_of(klass)
        generated_records.reverse_each do |path, object|
          next unless object.instance_of?(klass)
          next if ancestor_path?(path)

          return object
        end
        nil
      end

      def ancestor_path?(record_path)
        current_path = current.path
        record_path.length < current_path.length &&
          current_path[0, record_path.length] == record_path
      end
      private :ancestor_path?

      def push(klass)
        previous = current
        top_level = previous.depth.zero?
        enforce_depth_limit(previous, klass)

        reset_per_bake_caches! if top_level
        Fiber[STORAGE_KEY] = previous.append(klass)
        yield
      ensure
        Fiber[STORAGE_KEY] = previous
        reset_per_bake_caches! if top_level
      end

      # Each public bake gets fresh record, graph and condition state; a
      # declaration block that bakes again reads it but never writes back.
      def reset_per_bake_caches!
        Fiber[RECORDS_KEY] = []
        Fiber[GRAPH_CACHE_KEY] = {}
        Fiber[CONDITIONS_KEY] = {}
        Fiber[UNIQUE_VALUES_KEY] = {}
      end
      private :reset_per_bake_caches!

      private

      def enforce_depth_limit(previous, klass)
        limit = FactoryBakery.max_bake_depth
        next_depth = previous.depth + 1
        return unless next_depth > limit

        path = (previous.path + [klass]).map { |entry| class_name(entry) }.join(' -> ')
        raise NestingTooDeepError,
              "bake nesting exceeded max_bake_depth (#{limit}): #{path}"
      end

      def class_name(klass)
        klass.respond_to?(:name) && klass.name ? klass.name : klass.to_s
      end
    end

    # The names explicitly decided at this bake's higher layers (declarations,
    # overrides, initialize_with and omissions). Core fills it while resolving
    # values; plugins read it after instantiation so object-level auto-builders
    # can honour the same precedence the heuristic layer already applies.
    attr_accessor :taken_names

    # The same names before alias-group expansion. An auto-builder that must
    # tell an explicit assignment of an association from an override of one of
    # its columns reads this instead; plugins that honour the group as a whole
    # keep using `taken_names`.
    attr_accessor :explicit_names

    attr_reader :path

    def initialize(path)
      @path = path.freeze
    end

    def depth
      @path.length
    end

    # Records generated so far by the current top-level bake. Plugins read this
    # from the build context they are passed (for example to share objects).
    def generated_records
      self.class.generated_records
    end

    def append(klass)
      self.class.new(@path + [klass])
    end
  end
end
